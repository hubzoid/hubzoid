function formatWait(seconds: number): string {
  if (seconds < 60) return `${Math.ceil(seconds)} ${plural(Math.ceil(seconds), "second", "seconds")}`;
  const minutes = Math.ceil(seconds / 60);
  return `${minutes} ${plural(minutes, "minute", "minutes")}`;
}

