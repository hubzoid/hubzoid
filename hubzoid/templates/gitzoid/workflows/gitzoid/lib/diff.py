"""Reading unified diffs: line numbers, the lines GitHub accepts comments on,
the diff as the model sees it, and where a line sits in its file."""
from __future__ import annotations

import re

HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")
# What the model reads first when a diff is bigger than its budget: code, then
# other files, then tests, then docs, then lockfiles (the dependency check reads those).
CODE = re.compile(r"\.(py|js|jsx|ts|tsx|mjs|cjs|go|rb|php|java|kt|rs|cs|swift|scala|c|cc|cpp|h|hpp)$")
TESTS = re.compile(r"(^|/)(tests?|__tests__|spec|e2e)/|(^|/)test_[^/]*$|_test\.\w+$|\.(test|spec)\.\w+$")
DOCS = re.compile(r"(?i)\.(md|mdx|rst|txt|adoc)$|(^|/)docs?/|(^|/)(changelog|license|notice)[^/]*$")
LOCKS = re.compile(r"(^|/)(requirements[^/]*\.lock|poetry\.lock|uv\.lock|Pipfile\.lock|package-lock\.json|"
                   r"yarn\.lock|pnpm-lock\.yaml|go\.sum|Cargo\.lock|Gemfile\.lock|composer\.lock)$")
BUILT_NAME = re.compile(r"(^|/)node_modules/|\.(min|bundle|chunk)\.(js|mjs|css)$|\.map$")
GENERATED = re.compile(r"(?i)code generated|do not edit|autogenerated|auto-generated")
FUNCTIONS = [re.compile(p) for p in (
    r"^\s*(?:async\s+)?def\s+(\w+)",                                  # Python, Ruby
    r"^\s*class\s+(\w+)",                                             # Python, JS, Java
    r"^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s*\*?\s*(\w+)",  # JS
    r"^\s*(?:export\s+)?(?:const|let|var)\s+(\w+)\s*=\s*(?:async\s*)?(?:\([^)]*\)|\w+)\s*=>",  # JS arrows
    r"^func\s+(?:\([^)]*\)\s*)?(\w+)",                                # Go
    r"^\s*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)",          # Rust
    r"^\s*(?:public|private|protected|internal)\s+[\w<>\[\],\s]*?(\w+)\s*\(",  # Java, C#, Kotlin
)]


def walk(patch: str):
    """Yield (kind, new_line_or_None, text) per diff line; kind is +, - or space."""
    new = 0
    for raw in (patch or "").splitlines():
        m = HUNK.match(raw)
        if m:
            new = int(m.group(1)) - 1
            continue
        if raw.startswith("\\"):
            continue
        if raw.startswith("-"):
            yield "-", None, raw[1:]
            continue
        new += 1
        yield ("+" if raw.startswith("+") else " "), new, raw[1:]


def added_lines(patch: str) -> list[tuple[int, str]]:
    return [(n, t) for kind, n, t in walk(patch) if kind == "+"]


def commentable(files: list[dict]) -> set[tuple[str, int]]:
    """Lines GitHub accepts an inline comment on: added and context lines."""
    return {(f["filename"], n) for f in files for kind, n, _ in walk(f.get("patch") or "") if n}


def priority(f: dict) -> int:
    name = f["filename"]
    if LOCKS.search(name):
        return 4
    if TESTS.search(name):
        return 2
    if CODE.search(name):
        return 0  # code first, even in a docs/ folder
    if DOCS.search(name) and not re.search(r"(^|/)requirements[^/]*\.txt$", name):
        return 3
    return 1


def is_built(f: dict) -> bool:
    """Large build output and minified or generated code, which nobody reviews
    line by line. A change under 20 KB is always read, whatever its name or
    header says, so neither can hide a small hand-written file."""
    lines = list(walk(f.get("patch") or ""))
    added = [t for kind, _, t in lines if kind == "+"]
    size = sum(map(len, added))
    if size < 20_000:
        return False
    header = "\n".join(t for _, n, t in lines if n and n <= 5)  # the file's own first lines, added or not
    if BUILT_NAME.search(f["filename"]) or GENERATED.search(header):
        return True
    return max(map(len, added)) > 1000 and size / len(added) > 200


def format_diff(files: list[dict], budget: int, built: list[str] | None = None) -> tuple[str, list[str]]:
    """The diff with new-file line numbers, so the model can cite exact lines,
    and the files left out because the budget ran out. Code goes first, so a
    big change spends the budget on what matters; build output is collected
    in `built` (when given) instead of being read."""
    parts, used, left_out = [], 0, []
    for f in sorted(files, key=priority):
        if built is not None and is_built(f):
            built.append(f["filename"])
            continue
        head = f"### {f['filename']} ({f.get('status', 'modified')}, +{f.get('additions', 0)} -{f.get('deletions', 0)})"
        if not f.get("patch"):
            if f.get("status") == "renamed" and not f.get("additions") and not f.get("deletions"):
                body = "(rename only; no content change)"
            else:
                left_out.append(f["filename"])
                continue
        else:
            body = "\n".join(f"{n:>5} +{t}" if kind == "+" else f"{n:>5}  {t}" if kind == " " else f"      -{t}"
                             for kind, n, t in walk(f["patch"]))
        block = f"{head}\n{body}\n"
        if used + len(block) > budget:
            left_out.append(f["filename"])
            continue
        parts.append(block)
        used += len(block)
    return "\n".join(parts), left_out


def numbered_window(text: str, line: int, radius: int = 80) -> str:
    """The whole file when short, else `radius` lines either side of `line`."""
    lines = text.splitlines()
    if len(lines) <= 2 * radius:
        start, end = 0, len(lines)
    else:
        start, end = max(0, line - radius - 1), min(len(lines), line + radius)
    return "\n".join(f"{i + 1:>5}  {lines[i]}" for i in range(start, end))


def enclosing_function(text: str | None, line: int | None) -> str:
    """The nearest function or class defined at or above `line`, or ''."""
    if not text or not line:
        return ""
    lines = text.splitlines()
    if 0 < line <= len(lines) and lines[line - 1].lstrip().startswith("@"):
        for j in range(line, min(line + 6, len(lines))):  # a decorator belongs to the function below it
            for pattern in FUNCTIONS:
                m = pattern.match(lines[j])
                if m:
                    return m.group(1)
    for i in range(min(line, len(lines)) - 1, -1, -1):
        for pattern in FUNCTIONS:
            m = pattern.match(lines[i])
            if m:
                return m.group(1)
    return ""


def anchor(text: str | None, line: int | None, radius: int = 2) -> str:
    """The code around a line with whitespace squeezed: how a finding is found
    again after edits move it, and how GitZoid tells that its code changed."""
    if not text or not line:
        return ""
    lines = text.splitlines()
    if line > len(lines):
        return ""
    window = lines[max(0, line - 1 - radius): line + radius]
    return "\n".join(" ".join(x.split()) for x in window if x.strip())


def find_anchor(text: str | None, anchor_text: str) -> int | None:
    """The line where `anchor_text` now sits (its middle line), or None when
    the code it described is gone."""
    if not text or not anchor_text:
        return None
    want = anchor_text.split("\n")
    squeezed = [" ".join(x.split()) for x in text.splitlines()]
    index = [(i, s) for i, s in enumerate(squeezed) if s]
    flat = [s for _, s in index]
    for start in range(len(flat) - len(want) + 1):
        if flat[start:start + len(want)] == want:
            return index[start + len(want) // 2][0] + 1
    return None


def parse_unified(diff_text: str) -> list[dict]:
    """A `git diff` as GitHub-style file entries, for reviewing local changes."""
    files: list[dict] = []
    current = None
    for raw in diff_text.splitlines():
        if raw.startswith("diff --git "):
            m = re.match(r"diff --git a/(.+?) b/(.+)$", raw)
            current = {"filename": m.group(2) if m else raw.split()[-1], "status": "modified",
                       "patch_lines": [], "additions": 0, "deletions": 0}
            files.append(current)
            continue
        if current is None:
            continue
        if raw.startswith("new file mode"):
            current["status"] = "added"
        elif raw.startswith("deleted file mode"):
            current["status"] = "removed"
        elif raw.startswith(("index ", "--- ", "+++ ", "similarity ", "rename ", "old mode", "new mode")):
            if raw.startswith("+++ b/"):
                current["filename"] = raw[6:]
            continue
        elif raw.startswith("@@") or current["patch_lines"]:
            current["patch_lines"].append(raw)
            if raw.startswith("+"):
                current["additions"] += 1
            elif raw.startswith("-"):
                current["deletions"] += 1
    for f in files:
        f["patch"] = "\n".join(f.pop("patch_lines"))
    return files
